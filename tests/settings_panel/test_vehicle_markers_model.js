const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const context = {window:{},JSON,Math,Object,Array,String,Number};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../../mod/res/gui/gameface/mods/driftkings/settings_window/js/vehicle_markers_model.js'),'utf8'),context);
const model = context.window.DK.vehicleMarkerModel;
const sample = {group:'enemy',alt:false,blind:false,hp:50,name:'<b>unsafe</b>'};
const raw = {customFields:{enabled:true,enemy:{normal:[{format:'{{hp}}',x:12}],extended:[{format:'{{name}}'}]}}};
let state = model.state(raw,sample);
assert.strictEqual(state.fields[0].x,12);
assert.strictEqual(model.text('{{hp}}/{{maxHp}} {{hpPercent}}%',state.config,sample),'775/1550 50%');
assert.strictEqual(model.text('{{name}}',state.config,sample),'&lt;b&gt;unsafe&lt;/b&gt;');
assert.strictEqual(model.teamColor(state.config,sample),'#FF7777');
assert.strictEqual(model.teamColor(state.config,Object.assign({},sample,{blind:true})),'#C48CFF');
assert.strictEqual(model.hpColor(state.config,sample),'#FFDD66');
assert.strictEqual(model.text('{{hp}}',state.config,Object.assign({},sample,{group:'dead'})),'0');
assert.strictEqual(model.text('{{c:dmg}} -{{dmg}}',state.config,sample,310),'#FFDD66 -310');
assert.strictEqual(model.state(raw,Object.assign({},sample,{alt:true})).fields[0].format,'{{name}}');
assert.strictEqual(model.state(raw,Object.assign({},sample,{group:'ally'})).fields,null,'unconfigured mode preserves native text');
state.fields[0].x=90;
assert.strictEqual(raw.customFields.enemy.normal[0].x,12);
const palettes = [
    {name:'A',colors:model.clone(model.defaults.colors),damageColors:{player:'#111111'}},
    {name:'B',colors:model.clone(model.defaults.colors),damageColors:{player:'#222222'}}
];
palettes[1].colors.team.enemy='#123456';
palettes[1].colors.hp=[{value:10.4,color:'#010101'},{value:101,color:'#020202'}];
const linked = model.state({colorRating:1},sample,palettes).config;
assert.strictEqual(model.teamColor(linked,sample),'#123456');
assert.strictEqual(model.hpColor(linked,{hp:10.4}),'#020202');
assert.strictEqual(model.hpColor(linked,{hp:100}),'#020202');
assert.strictEqual(model.text('{{c:dmg}}',linked,sample,100),'#222222');
assert.strictEqual(model.state({colorRating:1,colors:{team:{enemy:'#ABCDEF'}}},sample,palettes).config.colors.team.enemy,'#ABCDEF');
const layouts = {schemaVersion:2,markers:{enabled:true},customFields:{enabled:true},healthBar:{enabled:true,x:-35},icons:{enabled:true},damageText:{enabled:true}};
let contextIndex=0;
['ally','enemy'].forEach(team => {
    ['markers','customFields','healthBar','icons','damageText'].forEach(key => { layouts[key][team]={}; });
    ['alive','dead'].forEach(life => {
        ['markers','customFields','healthBar','icons','damageText'].forEach(key => { layouts[key][team][life]={}; });
        ['normal','extended'].forEach(mode => {
            const index=++contextIndex;
            layouts.customFields[team][life][mode]=[{format:String(index)}];
            layouts.healthBar[team][life][mode]={x:index};
            layouts.icons[team][life][mode]={level:{x:index}};
            layouts.damageText[team][life][mode]={rise:index};
            layouts.markers[team][life][mode]={levelIcon:index%2===0};
            const resolved = model.state(layouts,{group:team,state:life,alt:mode==='extended',hp:70});
            assert.strictEqual(resolved.fields[0].format,String(index));
            assert.strictEqual(resolved.config.healthBar.x,index);
            assert.strictEqual(resolved.config.icons.level.x,index);
            assert.strictEqual(resolved.config.damageText.rise,index);
            assert.strictEqual(resolved.native.levelIcon,index%2===0);
        });
    });
});
assert.strictEqual(layouts.healthBar.x,-35);
palettes[1].colors.team.allyDead='#AABBCC';
assert.strictEqual(model.teamColor(model.state(layouts,sample,palettes).config,{group:'ally',state:'dead'}),'#AAAAAA');
assert.strictEqual(model.teamColor(palettes[1],{group:'ally',state:'dead'}),'#AABBCC');
const ratingConfig=model.state({ratingType:'wnx'},sample).config;
assert.strictEqual(model.text('{{r}} {{c:xr}}',ratingConfig,sample),'1800 #02C9B3');
assert.strictEqual(model.text('{{wn8}} {{eff}} {{wnx}}',ratingConfig,sample),'2000 1400 1800');
assert.strictEqual(model.text('{{xvm-stat?100|0}}',ratingConfig,Object.assign({},sample,{statsAvailable:false})),'0');
assert.strictEqual(model.text('{{r|--}}',ratingConfig,Object.assign({},sample,{statsAvailable:false})),'--');
assert.strictEqual(model.text('{{xvm-stat?{{r}}|--}}',ratingConfig,sample),'1800');
assert.strictEqual(model.text('{{r%.1f}}',ratingConfig,sample),'1800.0');
assert.strictEqual(model.ratingField(false).textFormat.color,'{{c:xr}}');
assert.strictEqual(model.ratingField(true).format,'{{r}}');
const conditionCases=JSON.parse(fs.readFileSync(path.join(__dirname,'../fixtures/vehicle_marker_conditions.json'),'utf8'));
conditionCases.cases.forEach(entry => assert.strictEqual(model.condition(entry[0],conditionCases.values),entry[1],entry[0]));
assert.strictEqual(model.condition('distance<=500',{distance:null}),false);
assert.strictEqual(model.condition('distance!=0',{distance:null}),false);
assert.strictEqual(model.text('{{enemy&&hp-ratio<=50?100|0}}',state.config,sample),'100');
assert.strictEqual(model.text('{{distance|--}} m',state.config,Object.assign({},sample,{distance:420})),'420 m');
assert.strictEqual(model.text('{{distance|--}} m',state.config,Object.assign({},sample,{distance:null})),'-- m');
assert.strictEqual(model.text('{{r|--}}',ratingConfig,Object.assign({},sample,{anonym:true})),'--');
const authorConfig=model.state({damageText:{enabled:true,sources:{player:{x:-80,duration:1},squad:{x:40,rise:100,format:'S {{dmg}}'}}}},sample).config;
assert.strictEqual(model.damageStyle(authorConfig,'player').x,-80);
assert.strictEqual(model.damageStyle(authorConfig,'squad').x,40);
assert.strictEqual(model.damageStyle(authorConfig,'other').x,-100);
assert.strictEqual(model.damageStyle(authorConfig,'squad').duration,2);
const ordinary=model.damageEvent(310,'squad','shot',0), explosion=model.damageEvent(310,'squad','shot',-1);
assert.strictEqual(ordinary.blowup,false);
assert.strictEqual(explosion.blowup,true);
assert.strictEqual(model.text('{{dmg-source}} {{dmg-kind}} {{dmg}} {{dmg-ratio}}%',authorConfig,sample,explosion),'squad explosion 310 20%');
assert.strictEqual(model.text('{{dmg-source==\'squad\'?S|X}}',authorConfig,sample,ordinary),'S');
console.log('Vehicle marker sample: macros, team/HP/colorblind colors and normal/ALT passed');

const references = {schemaVersion:2,def:{text:{format:'{{turret}}',x:12}},customFields:{enabled:true,enemy:{alive:{normal:[{$ref:{path:'def.text'},x:24}]}}}};
const referenceState=model.state(references,sample);
assert.strictEqual(referenceState.fields[0].x,24);
assert.strictEqual(references.def.text.x,12);
assert.strictEqual(model.text('{{turret}}',referenceState.config,Object.assign({},sample,{turret:'high'})),'*');
assert.strictEqual(model.text('{{stock-turret?yes|no}}',referenceState.config,Object.assign({},sample,{turret:'low'})),'yes');
assert.throws(()=>model.resolve({def:{a:'${def.a}'}}));
assert.throws(()=>model.resolve({field:'${def.missing}'}));
assert.strictEqual(model.state({},sample).config.healthBar.fill.alpha,100);
assert.strictEqual(model.state({},sample).config.icons.actionMarker.deadAlpha,100);
